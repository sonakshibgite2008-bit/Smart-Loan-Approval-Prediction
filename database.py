import os
from sqlalchemy import create_engine, text
from sqlalchemy.orm import declarative_base, sessionmaker
from urllib.parse import quote_plus
from config import DB_HOST, DB_NAME, DB_PASSWORD, DB_PORT, DB_USER
# =========================================================
# DATABASE URL
# =========================================================

def build_database_url():

    # If DATABASE_URL exists in environment, use it
    database_url = os.environ.get("DATABASE_URL")

    if database_url:
        return database_url

    # PostgreSQL
    if DB_HOST and DB_NAME and DB_USER:

        password = "" if DB_PASSWORD is None else str(DB_PASSWORD)
        encoded_password = quote_plus(password)

        port = DB_PORT or "5432"

        return (
            f"postgresql+psycopg2://"
            f"{DB_USER}:{encoded_password}"
            f"@{DB_HOST}:{port}/{DB_NAME}"
        )

    # Fallback SQLite
    return "sqlite:///./database/app.db"


DATABASE_URL = build_database_url()

print("DATABASE URL:", DATABASE_URL)


# =========================================================
# ENGINE
# =========================================================

engine = create_engine(
    DATABASE_URL,
    pool_pre_ping=True
)


# =========================================================
# SESSION
# =========================================================

SessionLocal = sessionmaker(
    autocommit=False,
    autoflush=False,
    bind=engine
)


# =========================================================
# BASE
# =========================================================

Base = declarative_base()


# =========================================================
# INITIALIZE DATABASE TABLES
# =========================================================

def initialize_database():

    if engine.dialect.name == "sqlite":

        users_sql = """
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            full_name TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            phone TEXT,
            password TEXT NOT NULL,
            role TEXT DEFAULT 'customer'
        )
        """

        prediction_sql = """
        CREATE TABLE IF NOT EXISTS prediction_history (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER,
            gender TEXT,
            married TEXT,
            education TEXT,
            income REAL,
            loan_amount REAL,
            property_area TEXT,
            result TEXT
        )
        """

        documents_sql = """
        CREATE TABLE IF NOT EXISTS documents (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            document_type TEXT NOT NULL,
            original_filename TEXT NOT NULL,
            stored_filename TEXT NOT NULL,
            file_path TEXT NOT NULL,
            uploaded_at TEXT NOT NULL,
            status TEXT DEFAULT 'pending',
            FOREIGN KEY(user_id) REFERENCES users(id)
        )
        """

    else:

        users_sql = """
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            full_name TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            phone TEXT,
            password TEXT NOT NULL,
            role TEXT DEFAULT 'customer'
        )
        """

        prediction_sql = """
        CREATE TABLE IF NOT EXISTS prediction_history (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER,
            gender TEXT,
            married TEXT,
            education TEXT,
            income REAL,
            loan_amount REAL,
            property_area TEXT,
            result TEXT
        )
        """

        documents_sql = """
        CREATE TABLE IF NOT EXISTS documents (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL,
            document_type TEXT NOT NULL,
            original_filename TEXT NOT NULL,
            stored_filename TEXT NOT NULL,
            file_path TEXT NOT NULL,
            uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            status TEXT DEFAULT 'pending',
            FOREIGN KEY(user_id) REFERENCES users(id)
        )
        """

    with engine.begin() as conn:

        conn.execute(text(users_sql))

        conn.execute(text(prediction_sql))

        conn.execute(text(documents_sql))


# Run database initialization
initialize_database()


# =========================================================
# DATABASE DEPENDENCY
# =========================================================

def get_db():

    db = SessionLocal()

    try:
        yield db

    finally:
        db.close()